<#
.SYNOPSIS
Ensures powershell-yaml is available for YAML parsing.

.DESCRIPTION
Uses an already available ConvertFrom-Yaml command or imports the installed
powershell-yaml module. If neither is available, repairs PSGallery registration
when necessary, then installs and imports powershell-yaml from PSGallery.
#>

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

if (Get-Command ConvertFrom-Yaml -ErrorAction SilentlyContinue)
{
    return
}

if (Get-Module -ListAvailable -Name powershell-yaml)
{
    Import-Module powershell-yaml -ErrorAction Stop
    return
}

$gallery = Get-PSRepository -Name PSGallery -ErrorAction SilentlyContinue
if ($null -eq $gallery -or [string]::IsNullOrWhiteSpace([string]$gallery.SourceLocation))
{
    if ($null -ne $gallery)
    {
        Unregister-PSRepository -Name PSGallery -ErrorAction Stop
    }

    Register-PSRepository -Default -ErrorAction Stop
    $gallery = Get-PSRepository -Name PSGallery -ErrorAction SilentlyContinue
}

if ($null -eq $gallery -or [string]::IsNullOrWhiteSpace([string]$gallery.SourceLocation))
{
    throw 'PSGallery has no usable source location after default registration.'
}

try
{
    Install-Module -Name powershell-yaml -Repository PSGallery -Scope CurrentUser -Force -AllowClobber -ErrorAction Stop
    Import-Module powershell-yaml -ErrorAction Stop
}
catch
{
    throw "Failed to install or import powershell-yaml from PSGallery '$($gallery.SourceLocation)': $($_.Exception.Message)"
}
